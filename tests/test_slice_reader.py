def test_review_damaged_entries_give_unreadable(monkeypatch: pytest.MonkeyPatch) -> None:
    data = sliced_3mf()
    # unknown compression method of the G-code entry (byte patch in the local and central header)
    archive = zipfile.ZipFile(io.BytesIO(data))
    info = archive.getinfo("Metadata/plate_1.gcode")
    patched = bytearray(data)
    for marker in (b"PK\x03\x04", b"PK\x01\x02"):
        start = 0
        while (start := data.find(marker, start)) != -1:
            offset = start + (8 if marker == b"PK\x03\x04" else 10)
            name_at = start + (30 if marker == b"PK\x03\x04" else 46)
            if data[name_at : name_at + len(info.filename)] == info.filename.encode():
                patched[offset : offset + 2] = (99).to_bytes(2, "little")
            start += 4
    fails(bytes(patched), "unreadable")


